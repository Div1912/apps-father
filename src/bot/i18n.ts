export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let text = translations[lang]?.[key] ?? translations.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, "g"), String(v));
      text = text.replace(new RegExp(`\\$\\{${k}\\}`, "g"), `$${v}`);
    }
  }
  return text;
}

export const LANG_NAMES: Record<Lang, string> = {
  en: "English",
  ru: "Русский",
  ua: "Українська",
};

export function langName(lang: Lang): string {
  return LANG_NAMES[lang] || LANG_NAMES.en;
}

export function translateStatus(lang: Lang, status: string): string {
  const key = `status_${status}`;
  const translated = translations[lang]?.[key];
  return translated || status;
}

const FEATURE_KEYS: Record<string, { label: string; desc: string }> = {
  stars_payment: { label: "feature_stars_payment", desc: "feature_stars_payment_desc" },
  ton_payment: { label: "feature_ton_payment", desc: "feature_ton_payment_desc" },
  admin_panel: { label: "feature_admin_panel", desc: "feature_admin_panel_desc" },
  disable_splash: { label: "feature_disable_splash", desc: "feature_disable_splash_desc" },
};

export function translateFeatureLabel(lang: Lang, featureId: string): string | null {
  const keys = FEATURE_KEYS[featureId];
  if (!keys) return null;
  return t(lang, keys.label);
}

export function translateFeatureDesc(lang: Lang, featureId: string): string | null {
  const keys = FEATURE_KEYS[featureId];
  if (!keys) return null;
  return t(lang, keys.desc);
}
